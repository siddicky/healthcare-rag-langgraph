"""
Multi-turn conversation dataset loading + LangSmith dataset upsert.

The source of truth is ``evals/multiturn_dataset.json`` (version-controlled).
``sync_dataset`` pushes it to LangSmith idempotently: example UUIDs are derived
from the stable ``id`` field (uuid5, same trick as :mod:`evals.dataset`), so
re-running updates rather than duplicates.

Two kinds of conversation live in the same file:

``kind == "scripted"``
    A fixed list of ``turns``. Each turn carries its own expectations
    (``expected_behavior``, ``reference_answer``, ``must_mention``,
    ``must_not_mention``, ``depends_on_turns``, ``expected_source_*``), so the
    per-turn evaluators can score it exactly like a single-turn golden example.

``kind == "simulated"``
    A persona (``simulated_user.system``) plus an ``opening`` message. The user
    side of the conversation is generated by an LLM at run time (openevals
    ``run_multiturn_simulation``), so there are no per-turn references — only the
    conversation-level ``conversation_rubric``.

Both kinds carry a ``conversation_rubric`` with ``must_hold`` invariants (things
that must be true of the *whole* conversation) and an ``expected_final_state``.

``depends_on_turns`` is **1-based** (turn 1 is the first user message).
"""

from __future__ import annotations

import json
import uuid
from pathlib import Path
from typing import Any

from langsmith import Client

MULTITURN_PATH = Path(__file__).parent / "multiturn_dataset.json"
DEFAULT_DATASET_NAME = "healthcare-rag-multiturn"

# Namespace for deterministic example ids (never change, or ids will churn).
_NS = uuid.UUID("2c9a1f7b-6e54-4d0a-b3c8-0a7f2e4d6b19")

VALID_KINDS = {"scripted", "simulated"}


def _parse(text: str) -> list[dict[str, Any]]:
    """Accept a JSON array, a ``{"conversations": [...]}`` wrapper, or JSONL.

    The sibling dataset is hand-authored; being permissive here means a stray
    newline-delimited file does not silently produce an empty dataset.
    """
    stripped = text.strip()
    if not stripped:
        return []
    try:
        data = json.loads(stripped)
    except json.JSONDecodeError:
        return [json.loads(line) for line in stripped.splitlines() if line.strip()]
    if isinstance(data, dict):
        for key in ("conversations", "examples", "data"):
            if isinstance(data.get(key), list):
                return data[key]
        raise ValueError("multiturn dataset object has no 'conversations' list")
    if not isinstance(data, list):
        raise ValueError(f"unexpected multiturn dataset root type: {type(data).__name__}")
    return data


def _validate(conv: dict[str, Any]) -> None:
    """Fail loudly on schema mistakes rather than producing silently-empty runs."""
    cid = conv.get("id")
    if not cid:
        raise ValueError(f"conversation missing 'id': {conv!r:.200}")
    kind = conv.get("kind")
    if kind not in VALID_KINDS:
        raise ValueError(f"{cid}: kind must be one of {sorted(VALID_KINDS)}, got {kind!r}")
    if kind == "scripted":
        turns = conv.get("turns")
        if not turns:
            raise ValueError(f"{cid}: scripted conversation needs a non-empty 'turns' list")
        for i, t in enumerate(turns, start=1):
            if not (t.get("user") or "").strip():
                raise ValueError(f"{cid}: turn {i} has no 'user' text")
    else:
        su = conv.get("simulated_user") or {}
        if not (su.get("system") or "").strip():
            raise ValueError(f"{cid}: simulated conversation needs simulated_user.system")
        if not (su.get("opening") or "").strip():
            raise ValueError(f"{cid}: simulated conversation needs simulated_user.opening")


def n_turns(conv: dict[str, Any]) -> int:
    """Number of user turns the conversation will play (upper bound for simulated)."""
    if conv.get("kind") == "simulated":
        return int((conv.get("simulated_user") or {}).get("max_turns") or 6)
    return len(conv.get("turns") or [])


def load_conversations(path: Path = MULTITURN_PATH) -> list[dict[str, Any]]:
    """Load + validate the conversation file. Raises on duplicate or bad rows."""
    rows = _parse(path.read_text())
    for conv in rows:
        _validate(conv)
    ids = [c["id"] for c in rows]
    if len(ids) != len(set(ids)):
        dupes = sorted({i for i in ids if ids.count(i) > 1})
        raise ValueError(f"duplicate conversation ids in {path.name}: {dupes}")
    return rows


def to_langsmith_example(conv: dict[str, Any]) -> dict[str, Any]:
    """Map one conversation to a LangSmith example (inputs / outputs / metadata).

    ``inputs`` is everything the harness needs to *play* the conversation;
    ``outputs`` is everything the evaluators need to *score* it.
    """
    kind = conv["kind"]
    inputs: dict[str, Any] = {"conversation_id": conv["id"], "kind": kind}
    if kind == "simulated":
        su = dict(conv.get("simulated_user") or {})
        su.setdefault("max_turns", 6)
        su.setdefault("stop_when", "")
        inputs["simulated_user"] = su
    else:
        inputs["turns"] = [t["user"] for t in conv["turns"]]

    expectations = [
        {
            "expected_behavior": t.get("expected_behavior") or "answer",
            "reference_answer": t.get("reference_answer") or "",
            "must_mention": t.get("must_mention") or [],
            "must_not_mention": t.get("must_not_mention") or [],
            "depends_on_turns": t.get("depends_on_turns") or [],
            "expected_source_chunk_ids": t.get("expected_source_chunk_ids") or [],
            "expected_source_pages": t.get("expected_source_pages") or [],
            "notes": t.get("notes") or "",
        }
        for t in (conv.get("turns") or [])
    ]

    return {
        "id": uuid.uuid5(_NS, conv["id"]),
        "inputs": inputs,
        "outputs": {
            "turns": expectations,
            "conversation_rubric": conv.get("conversation_rubric") or {},
            "category": conv.get("category"),
            "kind": kind,
        },
        "metadata": {
            "example_id": conv["id"],
            "kind": kind,
            "category": conv.get("category"),
            "n_turns": n_turns(conv),
            "split": conv.get("split") or "core",
            "title": conv.get("title") or "",
            "notes": conv.get("notes") or "",
        },
    }


def sync_dataset(
    client: Client, name: str = DEFAULT_DATASET_NAME, path: Path = MULTITURN_PATH
) -> tuple[Any, int, int]:
    """Create the dataset if missing and upsert every conversation.

    Returns ``(dataset, created, updated)``.
    """
    rows = load_conversations(path)
    if client.has_dataset(dataset_name=name):
        ds = client.read_dataset(dataset_name=name)
    else:
        ds = client.create_dataset(
            dataset_name=name,
            description="Multi-turn conversations (scripted + LLM-simulated) for the healthcare RAG. "
            "Tests context carry-over, cross-turn consistency, safety drift and PII persistence. "
            "Source of truth: evals/multiturn_dataset.json",
        )
    existing = {e.id for e in client.list_examples(dataset_id=ds.id)}
    examples = [to_langsmith_example(r) for r in rows]
    to_create = [e for e in examples if e["id"] not in existing]
    to_update = [e for e in examples if e["id"] in existing]
    if to_create:
        client.create_examples(dataset_id=ds.id, examples=to_create)
    if to_update:
        client.update_examples(dataset_id=ds.id, updates=to_update)
    return ds, len(to_create), len(to_update)


if __name__ == "__main__":
    import argparse

    from dotenv import load_dotenv

    load_dotenv()
    ap = argparse.ArgumentParser(description="Upsert evals/multiturn_dataset.json to LangSmith")
    ap.add_argument("--dataset", default=DEFAULT_DATASET_NAME)
    ap.add_argument("--dataset-file", default=str(MULTITURN_PATH))
    args = ap.parse_args()
    ds, created, updated = sync_dataset(Client(), args.dataset, Path(args.dataset_file))
    print(f"dataset '{ds.name}' ({ds.id}): created={created} updated={updated}")
